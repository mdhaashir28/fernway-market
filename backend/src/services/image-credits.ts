// Where each catalogue photo comes from and under which licence.
//
// • Sample photos (/sample-images/...) are described in backend/seed-images/sources.json
//   — the one place to update when a sample photo is added or replaced
//   (then run `npm run image-credits` to refresh CREDITS.md).
// • Photos uploaded by staff carry the source they typed when uploading
//   (products.image_source / categories.image_source).
import fs from 'node:fs';
import path from 'node:path';
import { seedCategories, seedProducts } from '../db/seed-data.js';
import { backendDir } from '../env.js';

export interface SampleImageSource {
  /** File name inside seed-images/products or seed-images/categories. */
  file: string;
  /** What the photo is used for, e.g. "Toor Dal". */
  subject: string;
  /** The original file's title on Wikimedia Commons. */
  title: string;
  /** Link to the original file's page. */
  source: string;
  author: string;
  licence: string;
  licenceUrl: string | null;
  /** What was changed, e.g. "Cropped to a square and resized". */
  changes: string;
  /** For category photos that reuse a product photo. */
  copyOf?: string;
}

export interface SampleImageSources {
  products: SampleImageSource[];
  categories: SampleImageSource[];
}

/** Shown next to a photo (and on the Photo credits screen). */
export interface ImageCredit {
  /** "licensed" = a free-licence photo that must be credited; "store" = the store's own note. */
  kind: 'licensed' | 'store';
  author: string | null;
  licence: string | null;
  licenceUrl: string | null;
  sourceUrl: string | null;
  /** For store photos: what staff typed, e.g. "Taken in our shop". */
  note: string | null;
}

export const SOURCES_FILE = path.join(backendDir, 'seed-images', 'sources.json');

let cached: SampleImageSources | null = null;

export function sampleImageSources(): SampleImageSources {
  if (!cached) {
    try {
      cached = JSON.parse(fs.readFileSync(SOURCES_FILE, 'utf8')) as SampleImageSources;
    } catch {
      cached = { products: [], categories: [] };
    }
  }
  return cached;
}

const SAMPLE_URL = /^\/sample-images\/(?:(categories)\/)?([^/?#]+)$/;

/** The credit for a photo, or null when nothing is known about it. */
export function imageCredit(imageUrl: string | null | undefined, imageSource: string | null | undefined): ImageCredit | null {
  if (!imageUrl) return null;
  const match = imageUrl.match(SAMPLE_URL);
  if (match) {
    const list = match[1] ? sampleImageSources().categories : sampleImageSources().products;
    const entry = list.find((item) => item.file === match[2]);
    if (entry) {
      return { kind: 'licensed', author: entry.author, licence: entry.licence, licenceUrl: entry.licenceUrl, sourceUrl: entry.source, note: null };
    }
  }
  const note = imageSource?.trim();
  return note ? { kind: 'store', author: null, licence: null, licenceUrl: null, sourceUrl: null, note } : null;
}

// ---------------------------------------------------------------------------
// CREDITS.md (generated by `npm run image-credits`)
// ---------------------------------------------------------------------------
const cell = (text: string) => text.replace(/\|/g, '\\|');
const link = (text: string, url: string | null) => (url ? `[${cell(text)}](${url})` : cell(text));

/** The sample products that have no photo file (they show "Image needed"). */
export function productsNeedingImages(): { sku: string; name: string; category: string }[] {
  const dir = path.join(backendDir, 'seed-images', 'products');
  const files = new Set(fs.existsSync(dir) ? fs.readdirSync(dir).map((f) => path.parse(f).name) : []);
  const categoryName = new Map(seedCategories.map((c) => [c.slug, c.name]));
  return seedProducts
    .filter((p) => !files.has(p.sku))
    .map((p) => ({ sku: p.sku, name: p.name, category: categoryName.get(p.category) ?? p.category }));
}

export function renderCreditsMarkdown(sources: SampleImageSources = sampleImageSources()): string {
  const table = (title: string, rows: SampleImageSource[], folder: string) => [
    `| ${title} | File | Original | Author | Licence | Changes |`,
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map(
      (r) =>
        `| ${cell(r.subject)} | \`${folder}${r.file}\` | ${link(r.title, r.source)} | ${cell(r.author)} | ${link(r.licence, r.licenceUrl)} | ${cell(
          r.copyOf ? `${r.changes} (same photo as \`${r.copyOf}\`)` : r.changes,
        )} |`,
    ),
  ];
  const missing = productsNeedingImages();
  const byCategory = new Map<string, string[]>();
  for (const p of missing) byCategory.set(p.category, [...(byCategory.get(p.category) ?? []), `${p.name} (\`${p.sku}\`)`]);

  return [
    '# Catalogue photo credits',
    '',
    '<!-- Generated by `npm run image-credits` from sources.json. Edit sources.json, not this file. -->',
    '',
    'Every sample photo in `products/` and `categories/` comes from [Wikimedia Commons](https://commons.wikimedia.org)',
    'and is used under the free licence listed below. Each one was checked to clearly show its product or category.',
    'None of them are official brand images, and none were copied from shopping websites or search results.',
    'Photos of loose staples (rice, dals, spices) show the product itself, not the store\'s own packet.',
    '',
    '**Licences:** CC0 and Public domain need no credit. CC BY and CC BY-SA require crediting the author and linking to',
    'the licence (the apps do this on the product page and on the Photo credits screen); CC BY-SA also requires that',
    'changed versions (for example cropped ones) use the same licence. All photos were resized and compressed for phones.',
    '',
    `## Product photos (${sources.products.length})`,
    '',
    ...table('Product', sources.products, 'products/'),
    '',
    `## Category photos (${sources.categories.length})`,
    '',
    ...table('Category', sources.categories, 'categories/'),
    '',
    `## Products that still need a photo (${missing.length})`,
    '',
    'No freely licensed photo that clearly matches these products was found, so the apps show a clearly labelled',
    '**“Image needed”** placeholder (never a made-up packet, an emoji or an unrelated photo). In the staff dashboard,',
    'tick **Image needed only** on the Products page to list them.',
    '',
    ...[...byCategory.entries()].map(([category, names]) => `- **${category}:** ${names.join(', ')}`),
    '',
    'Branded packaging is protected by copyright and trademarks. Use photos you are allowed to use: photograph the',
    'packs on your own shelves, or use images your distributor or the brand gives you written permission to use.',
    '',
    '## Adding or replacing a photo',
    '',
    '- **In the staff dashboard (recommended):** Products → open the product → **Upload photo**, and fill in',
    '  **Where is this photo from?** (for example "Taken in our shop, Oct 2026"). Photos are resized and compressed',
    '  automatically and the source is shown with the photo. Managers can do the same for categories.',
    '- **For the sample data:** save the file as `products/<SKU>.jpg` (or `categories/<slug>.jpg`), add its entry to',
    '  `sources.json` (source page, author, licence, changes) and run `npm run image-credits`. The tests fail if a photo',
    '  has no entry or this file is out of date.',
    '',
  ].join('\n');
}
